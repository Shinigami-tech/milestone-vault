// One command to get a private, working copy of Milestone Vault on NEAR testnet:
//   1. creates four free testnet accounts (vault, auditor, demo client, demo freelancer) via the faucet
//   2. deploys and initialises the contract
//   3. gives the auditor a FUNCTION-CALL key that can only call `report` on the vault,
//      then DELETES the auditor's full-access key, so the auditor account cannot move money at all
//   4. writes everything to .env (git-ignored)
//
// Usage: npm run build:contract && npm run setup:testnet
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { Account, JsonRpcProvider, KeyPair, KeyPairSigner, actions } from "near-api-js";

const RPC = process.env.NEAR_RPC || "https://test.rpc.fastnear.com";
const provider = new JsonRpcProvider({ url: RPC });
const WASM = new URL("../contract/target/near/milestone_vault.wasm", import.meta.url).pathname;
const ENV = new URL("../.env", import.meta.url).pathname;

if (!existsSync(WASM)) { console.error("Build the contract first: npm run build:contract"); process.exit(1); }
if (existsSync(ENV) && !process.argv.includes("--force")) { console.error(".env already exists. Re-run with --force to create a new deployment."); process.exit(1); }

const prefix = "mv" + randomBytes(3).toString("hex");
const names = { vault: `${prefix}-vault.testnet`, auditor: `${prefix}-auditor.testnet`, client: `${prefix}-client.testnet`, freelancer: `${prefix}-dev.testnet` };
const keys = {};

async function createAccount(id) {
  const kp = KeyPair.fromRandom("ed25519");
  const r = await fetch("https://helper.nearprotocol.com/account", {
    method: "POST", headers: { "content-type": "application/json" },
    body: JSON.stringify({ newAccountId: id, newAccountPublicKey: kp.getPublicKey().toString() }),
  });
  if (!r.ok) throw new Error(`Faucet refused ${id}: ${r.status} ${(await r.text()).slice(0, 200)}`);
  console.log("  created", id);
  return kp.toString();
}

console.log("1/4 Creating testnet accounts with the faucet…");
for (const [role, id] of Object.entries(names)) keys[role] = await createAccount(id);
await new Promise((r) => setTimeout(r, 3000));

console.log("2/4 Deploying the contract…");
const vault = new Account(names.vault, provider, KeyPairSigner.fromSecretKey(keys.vault));
await vault.signAndSendTransaction({
  receiverId: names.vault,
  actions: [
    actions.deployContract(readFileSync(WASM)),
    actions.functionCall("new", { owner: names.vault, auditor: names.auditor }, 30_000_000_000_000n, 0n),
  ],
});
console.log("  deployed to", names.vault);

console.log("3/4 Locking down the auditor's keys…");
const auditor = new Account(names.auditor, provider, KeyPairSigner.fromSecretKey(keys.auditor));
const fcKey = KeyPair.fromRandom("ed25519");
await auditor.addFunctionCallAccessKey({
  publicKey: fcKey.getPublicKey(),
  contractId: names.vault,
  methodNames: ["report"],
  allowance: 500_000_000_000_000_000_000_000n, // 0.5 NEAR of gas, nothing else
});
await auditor.deleteKey(KeyPair.fromString(keys.auditor).getPublicKey());
const list = await provider.viewAccessKeyList({ accountId: names.auditor, finality: "final" }).catch(() => null);
console.log("  auditor keys now:", JSON.stringify(list?.keys?.map((k) => k.access_key.permission) || "see explorer"));

console.log("4/4 Writing .env…");
writeFileSync(ENV, `# Generated by scripts/setup-testnet.mjs — testnet only, never commit this file
NEAR_NETWORK=testnet
VAULT_CONTRACT=${names.vault}
AUDITOR_ACCOUNT=${names.auditor}
AUDITOR_KEY=${fcKey.toString()}
DEMO_CLIENT_ACCOUNT=${names.client}
DEMO_CLIENT_KEY=${keys.client}
DEMO_FREELANCER_ACCOUNT=${names.freelancer}
DEMO_FREELANCER_KEY=${keys.freelancer}
# Optional: private inference for the audit summary (https://cloud.near.ai). Verdicts never depend on it.
NEARAI_API_KEY=
NEARAI_MODEL=
PORT=8090
`);
console.log(`\nDone. Vault: https://testnet.nearblocks.io/address/${names.vault}\nNext: npm start`);
